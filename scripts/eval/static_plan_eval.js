function loadTrainingData(category) {
    const fileName = INTENT_TO_TRAINING_FILE[category] || INTENT_TO_TRAINING_FILE.DEFAULT;
    const filePath = join(PROJECT_ROOT, 'data', 'training', fileName);
    if (!existsSync(filePath)) {
        console.warn(`Training file not found: ${filePath}, falling back to crafting_examples.json`);
        const fallback = join(PROJECT_ROOT, 'data', 'training', 'crafting_examples.json');
        return JSON.parse(readFileSync(fallback, 'utf8'));
    }
    return JSON.parse(readFileSync(filePath, 'utf8'));
}

function selectRandomExamples(examples, count) {
    if (examples.length <= count) return [...examples];
    // Fisher-Yates shuffle for uniform random selection
    const shuffled = [...examples];
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled.slice(0, count);
}

// ─── Item Name Utilities ───────────────────────────────────────────

const WOOD_PREFIXES = [
    'oak_', 'birch_', 'spruce_', 'jungle_',
    'acacia_', 'dark_oak_', 'mangrove_', 'cherry_', 'bamboo_'
];

function normalizeItemName(name) {
    if (!name) return '';
    let n = name.toLowerCase();
    for (const prefix of WOOD_PREFIXES) {
        if (n.startsWith(prefix)) {
            n = n.slice(prefix.length);
            break;
        }
    }
    n = n.replace(/^deepslate_/, '');
    return n;
}

function itemsMatch(required, available) {
    if (!required || !available) return false;
    if (required === available) return true;
    if (normalizeItemName(required) === normalizeItemName(available)) return true;
    // Precondition names the mined block ("stone") but inventory holds what it
    // actually drops without Silk Touch ("cobblestone") — same gap as
    // plan_validator.js's BLOCK_DROP_ALIASES fallback, duplicated here because
    // this eval harness runs its own precondition simulation, not validate().
    return BLOCK_DROP_ALIASES[required] === available;
}

/**
 * Check if an available tool satisfies a required tool via tier system.
 * e.g., iron_pickaxe (tier 2) satisfies stone_pickaxe (tier 1) requirement.
 */
function toolSatisfies(required, available) {
    if (itemsMatch(required, available)) return true;
    const availTier = TOOL_TIERS[available];
    const reqTier = TOOL_TIERS[required];
    if (availTier !== undefined && reqTier !== undefined && availTier >= reqTier) {
        return true;
    }
    return false;
}

// ─── Plan Generation ───────────────────────────────────────────────

/**
 * Build prompt for a given condition and generate plan via LLM.
 * Includes retry logic for API errors and parse failures.
 */
async function generatePlan(model, fsl, task, condition, trainingExamples, maxRetries = 3, warmStart = false) {
    const userRequest = { input: task.prompt, intent: task.category };
    const warmInventory = (task.warm_inventory || []).map(item =>
        typeof item === 'string' ? { name: item, count: 1 } : item
    );
    const agentState = { inventory: warmStart ? warmInventory : [], nearbyBlocks: [] };

    let prompt;
    let examplesUsed = 0;

    switch (condition) {
        case 'no_retrieval':
            prompt = fsl.buildFewShotPrompt(userRequest, [], null);
            examplesUsed = 0;
            break;
        case 'random_retrieval': {
            const randomExs = selectRandomExamples(trainingExamples, 3);
            prompt = fsl.buildFewShotPrompt(userRequest, randomExs, agentState);
            examplesUsed = randomExs.length;
            break;
        }
        case 'bm25_retrieval': {
            const bm25 = new BM25Retriever(trainingExamples);
            const bm25Exs = bm25.search(userRequest.input, 3);
            prompt = fsl.buildFewShotPrompt(userRequest, bm25Exs, agentState);
            examplesUsed = bm25Exs.length;
            break;
        }
        case 'saer_cold':
            // Cold start: empty inventory — no prior tools assumed
            prompt = fsl.buildFewShotPrompt(userRequest, trainingExamples, agentState);
            examplesUsed = 3;
            break;
        case 'saer_warm': {
            // Warm start: populate agentState with task's warm_inventory
            const warmState = {
                inventory: (task.warm_inventory || []).map(item =>
                    typeof item === 'string' ? { name: item, count: 1 } : item
                ),
                nearbyBlocks: []
            };
            prompt = fsl.buildFewShotPrompt(userRequest, trainingExamples, warmState);
            examplesUsed = 3;
            break;
        }
        case 'sbert_retrieval': {
            // Dense retrieval: top-3 examples pre-computed by SBERT (all-MiniLM-L6-v2)
            // Retrieval map generated by scripts/eval/compute_sbert_retrieval.py
            const sbertSlugs = SBERT_RETRIEVAL_MAP[task.slug] || [];
            const sbertExs = sbertSlugs
                .map(slug => trainingExamples.find(ex => ex.slug === slug))
                .filter(Boolean);
            // Fallback to random if retrieval map is missing entries
            const sbertFinal = sbertExs.length >= 3 ? sbertExs : [
                ...sbertExs,
                ...selectRandomExamples(trainingExamples, 3 - sbertExs.length)
            ];
            prompt = fsl.buildFewShotPrompt(userRequest, sbertFinal, agentState);
            examplesUsed = sbertFinal.length;
            break;
        }
        // Legacy alias kept for backward compat
        case 'saer_full':
            prompt = fsl.buildFewShotPrompt(userRequest, trainingExamples, agentState);
            examplesUsed = 3;
            break;
        default:
            throw new Error(`Unknown condition: ${condition}`);
    }

    let lastRaw = null;
    let lastErrorType = 'unknown';

    for (let attempt = 1; attempt <= maxRetries; attempt++) {
        try {
            const aiResponse = await model.sendRequest(
                [{ role: 'user', content: prompt }],
                SYSTEM_PROMPT
            );

            // Detect swallowed API errors from qwen.js
            if (!aiResponse || aiResponse.includes('My brain disconnected')) {
                lastRaw = aiResponse || '(empty response)';
                lastErrorType = 'api_error';
                console.log(`  Attempt ${attempt}/${maxRetries}: API error (swallowed), retrying...`);
                if (attempt < maxRetries) await sleep(3000);
                continue;
            }

            const plan = fsl.parseExecutionPlan(aiResponse, task.prompt);

            if (!plan) {
                lastRaw = aiResponse;
                lastErrorType = 'parse_error';
                console.log(`  Attempt ${attempt}/${maxRetries}: Parse failed, retrying...`);
                if (attempt < maxRetries) await sleep(2000);
                continue;
            }

            return { plan, examplesUsed, promptLength: prompt.length, rawResponse: aiResponse, errorType: null };

        } catch (err) {
            lastRaw = err.message;
            lastErrorType = 'api_error';
            console.log(`  Attempt ${attempt}/${maxRetries}: ${err.message}, retrying...`);
            if (attempt < maxRetries) await sleep(3000);
        }
    }

    return { plan: null, examplesUsed, promptLength: prompt.length, rawResponse: lastRaw, errorType: lastErrorType };
}

// ─── Plan Correctness Validation ───────────────────────────────────

/**
 * Normalize preconditions from parsed plan steps.
 * Handles both structured objects and string formats.
 */
function parsePreconditionToken(token) {
    if (!token) return null;
    if (typeof token === 'object' && token.type) return token;

    const str = String(token).trim();

    // LLM sometimes writes "None", "None (assume ...)", or "none" to mean no prerequisites
    if (/^none\b/i.test(str)) return null;

    // Format: "type:name:count" or "type:name"
    const match = str.match(/^(item|station|access):([^:]+)(?::(\d+))?$/);
    if (match) {
        return { type: match[1], name: match[2], count: match[3] ? parseInt(match[3]) : 1 };
    }
    // Fallback: treat as item
    return { type: 'item', name: str, count: 1 };
}

/**
 * Get all commands from a step (action_cmd array or single command).
 */
function getStepCommands(step) {
    const cmds = [];
    if (step.action_cmd && step.action_cmd.length > 0) {
        cmds.push(...step.action_cmd);
    } else if (step.command) {
        cmds.push(step.command);
    }
    return cmds;
}

/**
 * Infer produces from a command string.
 */
// True if itemName is only "produced" via a craftRecipe() call for an item
// that genuinely exists in mcData but has zero real recipes (loot/trade-only
// items like iron_horse_armor). Deliberately does NOT flag item names mcData
// doesn't recognize at all (e.g. a hallucinated "oak_chest") — those are a
// separate, pre-existing fuzzy-name-matching leniency and out of scope here.
function isUnrecipedCraftClaim(itemName, cmds, resolver) {
    if (!resolver) return false;
    const hasCraftCmd = cmds.some(cmd => {
        const cm = cmd.match(/craftRecipe\(['"]([^'"]+)['"]/);
        return cm && cm[1] === itemName;
    });
    if (!hasCraftCmd) return false;
    const mcData = resolver._getMcData ? resolver._getMcData() : null;
    if (!mcData) return false;
    const itemId = mcData.itemsByName[itemName]?.id;
    if (itemId == null) return false;
    const recipes = mcData.recipes[String(itemId)];
    return !recipes || recipes.length === 0;
}

function inferProducesFromCommand(cmd, resolver = null) {
    if (!cmd) return [];

    const results = [];

    // smeltItem("raw_iron", 3) → iron_ingot
    const smeltMatch = cmd.match(/smeltItem\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
    if (smeltMatch) {
        const input = smeltMatch[1];
        const count = parseInt(smeltMatch[2]);
        const output = SMELTING_OUTPUTS[input];
        if (output) {
            results.push({ type: 'item', name: output, count });
        }
        return results;
    }

    // craftRecipe("iron_pickaxe", 1) → iron_pickaxe
    // Only credit production if a real mcData recipe exists — some LLM-generated
    // plans invoke craftRecipe on loot/trade-only items (e.g. iron_horse_armor)
    // that have no crafting recipe at all in vanilla Minecraft.
    const craftMatch = cmd.match(/craftRecipe\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
    if (craftMatch) {
        const item = craftMatch[1];
        if (isUnrecipedCraftClaim(item, [cmd], resolver)) {
            return results;
        }
        results.push({ type: 'item', name: item, count: parseInt(craftMatch[2]) });
        return results;
    }

    // collectBlocks("iron_ore", 3) → raw_iron (1.17+ drops raw materials)
    const collectMatch = cmd.match(/collectBlocks\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
    if (collectMatch) {
        const block = collectMatch[1];
        const count = parseInt(collectMatch[2]);
        // Raw ore mapping (1.17+ raw drops) + direct drops
        const rawOreMap = {
            'iron_ore': 'raw_iron',
            'deepslate_iron_ore': 'raw_iron',
            'gold_ore': 'raw_gold',
            'deepslate_gold_ore': 'raw_gold',
            'copper_ore': 'raw_copper',
            'deepslate_copper_ore': 'raw_copper',
            // Direct drops (no smelting)
            'diamond_ore': 'diamond',
            'deepslate_diamond_ore': 'diamond',
            'emerald_ore': 'emerald',
            'deepslate_emerald_ore': 'emerald',
            'coal_ore': 'coal',
            'deepslate_coal_ore': 'coal',
            'lapis_ore': 'lapis_lazuli',
            'deepslate_lapis_ore': 'lapis_lazuli',
            'redstone_ore': 'redstone',
            'deepslate_redstone_ore': 'redstone',
            'nether_quartz_ore': 'quartz',
            'ancient_debris': 'ancient_debris',
            // Block → drop differences (mining without Silk Touch)
            'stone': 'cobblestone',
            'deepslate': 'cobbled_deepslate',
            'clay': 'clay_ball',
            'grass_block': 'dirt'
        };
        const product = rawOreMap[block] || block;
        results.push({ type: 'item', name: product, count });
        // Mining gravel has a chance to drop flint instead of gravel; players
        // routinely over-mine gravel to farm flint for flint_and_steel, so
        // credit one flint alongside the gravel itself.
        if (block === 'gravel') {
            results.push({ type: 'item', name: 'flint', count: 1 });
        }
        return results;
    }

    // attack("zombie", true) → mob drop (e.g. rotten_flesh, gunpowder, ender_pearl)
    const attackMatch = cmd.match(/attack\(['"]([^'"]+)['"]/);
    if (attackMatch) {
        const mob = attackMatch[1];
        const mobDrops = {
            'zombie': 'rotten_flesh',
            'skeleton': 'bone',
            'spider': 'string',
            'cave_spider': 'string',
            'creeper': 'gunpowder',
            'enderman': 'ender_pearl',
            'slime': 'slime_ball',
            'blaze': 'blaze_rod',
            'wither_skeleton': 'bone',
            'witch': 'redstone',
            'cow': 'beef',
            'pig': 'porkchop',
            'chicken': 'chicken',
            'sheep': 'wool'
        };
        const drop = mobDrops[mob];
        if (drop) {
            // Use count 5 — mob attacks are goal-directed (!attack(mob, true) means
            // "kill repeatedly until done"), so a generous estimate ensures goal_count
            // checks pass for any reasonable task (e.g. kill_slime goal_count:2).
            results.push({ type: 'item', name: drop, count: 5 });
        }
        return results;
    }

    return results;
}

/**
 * Check if a collectBlocks command for a given block requires a pickaxe,
 * and if so, what tier.
 */
function getRequiredTool(blockName) {
    return ORE_TOOL_REQUIREMENTS[blockName] || null;
}

/**
 * Validate a plan's correctness.
 *
 * Returns { strict_pass, lenient_pass, pvr, issues, lenient_issues }
 */
export function validatePlanCorrectness(task, plan, initialInventory = [], resolver = null) {
    if (!plan || !plan.steps || plan.steps.length === 0) {
        return {
            strict_pass: false,
            lenient_pass: false,
            pvr: false,
            step_count: 0,
            step_efficiency: 0,
            issues: ['Plan is empty or could not be parsed'],
            lenient_issues: ['Plan is empty or could not be parsed']
        };
    }

    const issues = [];
    const lenientIssues = [];
    const steps = plan.steps;
    let goalAchieved = false;
    let allPreconditionsMet = true;

    // Track available items from prior steps' produces
    // Pre-seed with warm_inventory so validator accepts skipped prerequisite steps
    const availableItems = new Map(); // name → count
    for (const item of initialInventory) {
        const name = typeof item === 'string' ? item : item.name;
        const count = typeof item === 'string' ? 1 : (item.count || 1);
        availableItems.set(name, (availableItems.get(name) || 0) + count);
    }

    for (let i = 0; i < steps.length; i++) {
        const step = steps[i];
        const cmds = getStepCommands(step);

        // 1. Check goal achievement (explicit produces field)
        if (step.produces) {
            const produces = Array.isArray(step.produces) ? step.produces : [step.produces];
            for (const p of produces) {
                if (p.type === 'item' && itemsMatch(p.name, task.goal_item) &&
                    !isUnrecipedCraftClaim(p.name, cmds, resolver)) {
                    goalAchieved = true;
                }
            }
        }

        // 2. Check preconditions
        const preconds = (step.preconditions || [])
            .map(c => typeof c === 'string' ? parsePreconditionToken(c) : c)
            .filter(Boolean);

        for (const cond of preconds) {
            if (cond.type === 'access') continue; // access always satisfied in static eval
            if (cond.type === 'station') continue; // stations assumed available in static eval

            if (cond.type === 'item') {
                const required = cond.name;
                const count = cond.count || 1;
                let satisfied = false;

                // Check available items
                for (const [availName, availCount] of availableItems) {
                    if (toolSatisfies(required, availName)) {
                        if (availCount >= count) {
                            satisfied = true;
                            break;
                        }
                    } else if (itemsMatch(required, availName)) {
                        if (availCount >= count) {
                            satisfied = true;
                            break;
                        }
                    }
                }

                if (!satisfied) {
                    allPreconditionsMet = false;
                    const msg = `Step ${step.step}: missing ${required}${count > 1 ? ' x' + count : ''}`;
                    issues.push(msg);
                    lenientIssues.push(msg);
                }
            }
        }

        // 3. Check tool requirements for collectBlocks (strict + lenient)
        // Process commands sequentially: items produced by earlier commands within
        // the same step are available to later commands in that step.
        // Example: craftRecipe('wooden_pickaxe') followed by collectBlocks('stone')
        // must correctly recognize the pickaxe was just crafted.
        {
            const withinStepItems = new Map(availableItems);
            for (const cmd of cmds) {
                // Check tool requirement using inventory state AFTER prior cmds in this step
                const collectMatch = cmd.match(/collectBlocks\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
                if (collectMatch) {
                    const block = collectMatch[1];
                    const requiredTool = getRequiredTool(block);
                    if (requiredTool) {
                        let hasTool = false;
                        for (const [availName] of withinStepItems) {
                            if (toolSatisfies(requiredTool, availName)) {
                                hasTool = true;
                                break;
                            }
                        }
                        if (!hasTool) {
                            const msg = `Step ${step.step}: collecting ${block} requires ${requiredTool}, not available`;
                            issues.push(msg);
                            lenientIssues.push(msg);
                        }
                    }
                }
                // Add this command's produces to withinStepItems so subsequent
                // commands in this step can see them.
                for (const produced of inferProducesFromCommand(cmd, resolver)) {
                    if (produced && produced.type === 'item' && produced.name) {
                        withinStepItems.set(
                            produced.name,
                            (withinStepItems.get(produced.name) || 0) + (produced.count || 1)
                        );
                    }
                }
            }
        }

        // 3.5. Ingredient availability check for craftRecipe and smeltItem
        // Catches "magic crafting" where the LLM omits prerequisite collection steps.
        // Uses a within-step accumulator (withinStepAvail) so that commands earlier
        // in the same step's action_cmd list can satisfy later commands' ingredients
        // (e.g. craftRecipe('oak_planks') → craftRecipe('stick') in one step).
        if (resolver) {
            const withinStepAvail = new Map(availableItems);
            for (const cmd of cmds) {
                const craftMatch = cmd.match(/craftRecipe\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
                if (craftMatch) {
                    const item = craftMatch[1];
                    const goalCount = parseInt(craftMatch[2]) || 1;
                    const recipes = resolver.craftingRecipesFor(item);
                    if (recipes && recipes.length > 0) {
                        // Accept if ANY recipe variant can be satisfied (handles fungible inputs)
                        const anyVariantOk = recipes.some(recipe => {
                            const ops = Math.ceil(goalCount / (recipe.outputCount || 1));
                            return recipe.ingredients.every(ing =>
                                (withinStepAvail.get(ing.name) || 0) >= ing.count * ops
                            );
                        });
                        if (!anyVariantOk) {
                            // Report missing ingredients from the first recipe (best-effort)
                            const best = recipes[0];
                            const ops = Math.ceil(goalCount / (best.outputCount || 1));
                            const missing = best.ingredients
                                .filter(ing => (withinStepAvail.get(ing.name) || 0) < ing.count * ops)
                                .map(ing => `${ing.name} x${ing.count * ops}`);
                            const msg = `Step ${step.step}: craftRecipe("${item}", ${goalCount}) missing ingredients: ${missing.join(', ')}`;
                            issues.push(msg);
                            lenientIssues.push(msg);
                        }
                    }
                }

                const smeltMatch2 = cmd.match(/smeltItem\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
                if (smeltMatch2) {
                    const input = smeltMatch2[1];
                    const count = parseInt(smeltMatch2[2]) || 1;
                    // Skip wrong-name inputs — those are caught in section 4.
                    // Only check availability here for correctly-named inputs.
                    const wrongNames = ['iron_ore', 'gold_ore', 'copper_ore'];
                    if (!wrongNames.includes(input)) {
                        const avail = withinStepAvail.get(input) || 0;
                        if (avail < count) {
                            const msg = `Step ${step.step}: smeltItem("${input}", ${count}) needs ${count} but only ${avail} available`;
                            issues.push(msg);
                            lenientIssues.push(msg);
                        }
                    }
                }

                // Accumulate this command's outputs so subsequent commands in this
                // step can see them (mirrors the withinStepItems logic in section 3).
                for (const produced of inferProducesFromCommand(cmd, resolver)) {
                    if (produced && produced.type === 'item' && produced.name) {
                        withinStepAvail.set(
                            produced.name,
                            (withinStepAvail.get(produced.name) || 0) + (produced.count || 1)
                        );
                    }
                }
            }
        }

        // 4. Check smelting naming (strict only)
        for (const cmd of cmds) {
            const smeltMatch = cmd.match(/smeltItem\(['"]([^'"]+)['"]\s*,\s*(\d+)\)/);
            if (smeltMatch) {
                const input = smeltMatch[1];
                const rawOreCorrection = {
                    'iron_ore': 'raw_iron',
                    'gold_ore': 'raw_gold',
                    'copper_ore': 'raw_copper'
                };
                if (rawOreCorrection[input]) {
                    const correct = rawOreCorrection[input];
                    issues.push(
                        `Step ${step.step}: smeltItem("${input}") should be smeltItem("${correct}") — ` +
                        `Minecraft 1.17+ drops raw materials`
                    );
                    // NOT added to lenientIssues — naming issues forgiven in lenient mode
                }
            }
        }

        // 5. Add step's produces to available items
        let stepOutputs = [];
        if (step.produces) {
            stepOutputs = Array.isArray(step.produces) ? step.produces : [step.produces];
        }
        // Always ALSO infer from commands — picks up intermediate items (oak_log, raw_copper, etc.)
        // that explicit produces may omit when a step bundles multiple actions.
        // Only add items not already declared so we don't double-count.
        for (const cmd of cmds) {
            for (const inf of inferProducesFromCommand(cmd, resolver)) {
                if (!stepOutputs.some(s => s.name === inf.name)) {
                    stepOutputs.push(inf);
                }
            }
        }

        // Drop declared produces for items whose only action_cmd is a craftRecipe
        // call with no real mcData recipe (e.g. loot/trade-only items like
        // iron_horse_armor) — the LLM can hand-declare `produces` even when the
        // crafted item doesn't actually exist as a craftable recipe.
        stepOutputs = stepOutputs.filter(output =>
            !(output && output.type === 'item' && output.name &&
              isUnrecipedCraftClaim(output.name, cmds, resolver))
        );

        for (const output of stepOutputs) {
            if (output && output.type === 'item' && output.name) {
                const key = output.name;
                availableItems.set(key, (availableItems.get(key) || 0) + (output.count || 1));
            }
        }
    }

    // Final check: goal achievement via inferred produces in availableItems
    if (!goalAchieved) {
        for (const [name, count] of availableItems) {
            if (itemsMatch(name, task.goal_item) && count >= (task.goal_count || 1)) {
                goalAchieved = true;
                break;
            }
        }
    }

    if (!goalAchieved) {
        const msg = `Goal item "${task.goal_item}" not produced by any step`;
        issues.push(msg);
        lenientIssues.push(msg);
    }

    // Step efficiency
    const stepCount = steps.length;
    const stepEfficiency = task.min_steps > 0
        ? Math.min(1.0, task.min_steps / stepCount)
        : 0;

    const strictPass = issues.length === 0 && goalAchieved;
    const lenientPass = lenientIssues.length === 0 && goalAchieved;

    return {
        strict_pass: strictPass,
        lenient_pass: lenientPass,
        pvr: allPreconditionsMet && goalAchieved,
        step_count: stepCount,
        step_efficiency: Math.round(stepEfficiency * 100) / 100,
        issues,
        lenient_issues: lenientIssues
    };
}

// ─── Output Formatting ─────────────────────────────────────────────

function formatTimestamp() {
    const now = new Date();
    const pad = (n) => String(n).padStart(2, '0');
    return `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}` +
        `_${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
}

function buildSummary(results) {
    const levels = ['L1', 'L2', 'L3'];
    const byLevel = {};

    for (const level of levels) {
        const levelResults = results.filter(r => r.level === level);
        const total = levelResults.length;
        if (total === 0) continue;

        byLevel[level] = {
            total,
            strict_tcr: `${levelResults.filter(r => r.validation.strict_pass).length}/${total}`,
            lenient_tcr: `${levelResults.filter(r => r.validation.lenient_pass).length}/${total}`,
            pvr: `${levelResults.filter(r => r.validation.pvr).length}/${total}`,
            avg_step_efficiency: Math.round(
                levelResults.reduce((s, r) => s + r.validation.step_efficiency, 0) / total * 100
            ) / 100
        };
    }

    const total = results.length;
    const overall = {
        strict_tcr: `${results.filter(r => r.validation.strict_pass).length}/${total}`,
        lenient_tcr: `${results.filter(r => r.validation.lenient_pass).length}/${total}`,
        pvr: `${results.filter(r => r.validation.pvr).length}/${total}`,
        avg_step_efficiency: Math.round(
            results.reduce((s, r) => s + r.validation.step_efficiency, 0) / total * 100
        ) / 100
    };

    return { by_level: byLevel, overall };
}

function writeJSON(outputDir, timestamp, condition, data, seed = null) {
    const suffix = seed !== null ? `_s${seed}` : '';
    const filename = `eval_${timestamp}_${condition}${suffix}.json`;
    const path = join(outputDir, filename);
    writeFileSync(path, JSON.stringify(data, null, 2));
    console.log(`JSON results: ${path}`);
    return path;
}

function writeMarkdown(outputDir, timestamp, condition, data) {
    const filename = `eval_${timestamp}_${condition}_report.md`;
    const path = join(outputDir, filename);
    const lines = [];

    lines.push(`# Static Plan Evaluation Report`);
    lines.push('');
    lines.push(`**Date**: ${data.meta.timestamp}`);
    lines.push(`**Model**: ${data.meta.model}`);
    lines.push(`**Condition**: ${condition}`);
    lines.push(`**Tasks**: ${data.meta.completed_tasks}/${data.meta.total_tasks} completed`);
    lines.push('');

    // Summary table
    const summary = data.summary;
    lines.push(`## Summary`);
    lines.push('');
    lines.push('| Level | Strict TCR | Lenient TCR | PVR | Avg Efficiency |');
    lines.push('|-------|-----------|------------|-----|---------------|');

    for (const [level, stats] of Object.entries(summary.by_level)) {
        lines.push(
            `| ${level} | ${stats.strict_tcr} | ${stats.lenient_tcr} | ${stats.pvr} | ${stats.avg_step_efficiency} |`
        );
    }
    lines.push(
        `| **Overall** | **${summary.overall.strict_tcr}** | **${summary.overall.lenient_tcr}** | **${summary.overall.pvr}** | **${summary.overall.avg_step_efficiency}** |`
    );
    lines.push('');

    // Per-task details
    lines.push(`## Per-Task Results`);
    lines.push('');

    for (const task of data.tasks) {
        const v = task.validation;
        const strictIcon = v.strict_pass ? 'PASS' : 'FAIL';
        const lenientIcon = v.lenient_pass ? 'PASS' : 'FAIL';

        lines.push(`### ${task.slug} (${task.level})`);
        lines.push(`- Goal: ${task.goal_item}`);
        lines.push(`- Steps: ${v.step_count} (min: ${task.min_steps}, efficiency: ${v.step_efficiency})`);
        lines.push(`- Strict: ${strictIcon} | Lenient: ${lenientIcon} | PVR: ${v.pvr ? 'PASS' : 'FAIL'}`);

        if (v.issues.length > 0) {
            lines.push(`- Strict issues:`);
            for (const issue of v.issues) {
                lines.push(`  - ${issue}`);
            }
        }
        if (v.lenient_issues.length > 0 && v.lenient_issues.length !== v.issues.length) {
            lines.push(`- Lenient issues:`);
            for (const issue of v.lenient_issues) {
                lines.push(`  - ${issue}`);
            }
        }
        lines.push('');
    }

    writeFileSync(path, lines.join('\n'));
    console.log(`Markdown report: ${path}`);
    return path;
}

// ─── Main ──────────────────────────────────────────────────────────

function sleep(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
}

async function main() {
    console.log('=== SAER Static Plan Evaluator ===\n');

    const conditions = argv.mode ? [argv.mode] : CONDITIONS;
    const outputDir = argv.output || join(__dirname, 'results');
    mkdirSync(outputDir, { recursive: true });

    // Load eval tasks
    const tasksPath = join(__dirname, 'eval_tasks.json');
    let tasks = JSON.parse(readFileSync(tasksPath, 'utf8'));

    // Filter tasks
    if (argv.slug) {
        tasks = tasks.filter(t => t.slug === argv.slug);
        if (tasks.length === 0) {
            console.error(`No task found with slug: ${argv.slug}`);
            process.exit(1);
        }
    }
    if (argv.level) {
        tasks = tasks.filter(t => t.level === argv.level);
        if (tasks.length === 0) {
            console.error(`No tasks found for level: ${argv.level}`);
            process.exit(1);
        }
    }
    if (argv.category) {
        tasks = tasks.filter(t => t.category === argv.category.toUpperCase());
        if (tasks.length === 0) {
            console.error(`No tasks found for category: ${argv.category}`);
            process.exit(1);
        }
    }
    if (argv['only-tasks']) {
        const wanted = argv['only-tasks'].split(',').map(s => s.trim()).filter(Boolean);
        tasks = tasks.filter(t => wanted.includes(t.slug));
        // Fail loudly on a typo'd slug: a silently short task list would look
        // like a legitimate result and quietly corrupt the ablation.
        const missing = wanted.filter(w => !tasks.some(t => t.slug === w));
        if (missing.length > 0) {
            console.error(`--only-tasks: no such task slug(s): ${missing.join(', ')}`);
            process.exit(1);
        }
    }

    console.log(`Tasks: ${tasks.length}, Conditions: ${conditions.join(', ')}\n`);

    // Create model and FewShotLearning
    const profile = loadProfile(argv.profile);
    const modelConfig = getModelConfig(profile);
    const model = await createModel(modelConfig);
    const fsl = new FewShotLearning(argv.debug);
    // CRITICAL: propagate the mcData-backed resolver so SAER's ingredient/mining/prereq
    // dimensions are active. Without this, FewShotLearning's SAERScorer defaults to
    // RecipeResolver(null) → craftingRecipesFor/getRequiredTool return empty → those
    // dimensions collapse to constants and SAER degrades to keyword+level (≈ BM25).
    // (static_plan_eval_v2.js already carried this fix as "fix #6"; v1 omitted it.)
    fsl.setRecipeResolver(recipeResolver);

    if (argv['top-k'] !== 3) {
        fsl.topK = argv['top-k'];
        console.log(`top-k override: ${fsl.topK}`);
    }

    // Apply custom SAER weights if provided (weight ablation experiments)
    if (argv['saer-weights']) {
        const w = JSON.parse(argv['saer-weights']);
        fsl.setWeights(w);
        console.log(`SAER weights override: ${JSON.stringify(w)}`);
    }

    console.log(`Model: ${modelConfig.api}/${modelConfig.model}`);
    const timestamp = formatTimestamp();
    const numSeeds = argv.seeds || 1;

    // Multi-seed support: run full eval N times for statistical stability
    const allSeedOutputs = []; // [{condition, output}]

    for (let seed = 1; seed <= numSeeds; seed++) {
        if (numSeeds > 1) console.log(`\n${'='.repeat(50)}\n  SEED ${seed}/${numSeeds}\n${'='.repeat(50)}`);

    // Run each condition separately (incremental runs)
    for (const condition of conditions) {
        console.log(`\n--- Condition: ${condition}${numSeeds > 1 ? ` (seed ${seed})` : ''} ---\n`);

        const results = [];
        let completed = 0;
        let failed = 0;

        for (const task of tasks) {
            console.log(`[${condition}] ${task.slug} (${task.level})...`);

            try {
                let trainingExamples = loadTrainingData(task.category);
                if (argv['exclude-slugs']) {
                    const excludeSlugs = argv['exclude-slugs'].split(',').map(s => s.trim());
                    trainingExamples = trainingExamples.filter(e => !excludeSlugs.includes(e.slug));
                }
                const genResult = await generatePlan(model, fsl, task, condition, trainingExamples, argv.retries, argv.warm);

                if (!genResult.plan) {
                    console.log(`  FAILED (${genResult.errorType || 'unknown'})`);
                    results.push({
                        slug: task.slug,
                        level: task.level,
                        goal_item: task.goal_item,
                        min_steps: task.min_steps,
                        parse_success: false,
                        plan: null,
                        raw_response: genResult.rawResponse || null,
                        error_type: genResult.errorType || 'unknown',
                        validation: {
                            strict_pass: false,
                            lenient_pass: false,
                            pvr: false,
                            step_count: 0,
                            step_efficiency: 0,
                            issues: [`Plan ${genResult.errorType === 'api_error' ? 'generation failed (API error)' : 'parsing failed'}`],
                            lenient_issues: [`Plan ${genResult.errorType === 'api_error' ? 'generation failed (API error)' : 'parsing failed'}`]
                        },
                        examples_used: genResult.examplesUsed,
                        prompt_length: genResult.promptLength
                    });
                    failed++;
                } else {
                    const initialInv = (condition === 'saer_warm' || argv.warm) ? (task.warm_inventory || []) : [];
                    const validation = validatePlanCorrectness(task, genResult.plan, initialInv, recipeResolver);
                    const strictIcon = validation.strict_pass ? 'PASS' : 'FAIL';
                    const lenientIcon = validation.lenient_pass ? 'PASS' : 'FAIL';
                    console.log(`  ${validation.step_count} steps, strict=${strictIcon}, lenient=${lenientIcon}`);

                    results.push({
                        slug: task.slug,
                        level: task.level,
                        goal_item: task.goal_item,
                        min_steps: task.min_steps,
                        parse_success: true,
                        plan: {
                            steps: genResult.plan.steps,
                            target: genResult.plan.target
                        },
                        raw_response: genResult.rawResponse,
                        validation,
                        examples_used: genResult.examplesUsed,
                        prompt_length: genResult.promptLength
                    });
                    completed++;
                }
            } catch (err) {
                console.error(`  ERROR: ${err.message}`);
                results.push({
                    slug: task.slug,
                    level: task.level,
                    goal_item: task.goal_item,
                    min_steps: task.min_steps,
                    parse_success: false,
                    plan: null,
                    validation: {
                        strict_pass: false,
                        lenient_pass: false,
                        pvr: false,
                        step_count: 0,
                        step_efficiency: 0,
                        issues: [`Error: ${err.message}`],
                        lenient_issues: [`Error: ${err.message}`]
                    },
                    examples_used: 0,
                    prompt_length: 0
                });
                failed++;
            }

            // Rate limiting
            if (tasks.indexOf(task) < tasks.length - 1) {
                const delay = INTER_TASK_DELAY_MS + (argv['task-delay'] || 0);
                await sleep(delay);
            }
        }

        // Build output
        const output = {
            meta: {
                timestamp: new Date().toISOString(),
                model: modelConfig.model || 'unknown',
                condition,
                total_tasks: tasks.length,
                completed_tasks: completed,
                failed_tasks: failed
            },
            tasks: results,
            summary: buildSummary(results)
        };

        writeJSON(outputDir, timestamp, condition, output, numSeeds > 1 ? seed : null);
        if (numSeeds === 1 || seed === numSeeds) {
            writeMarkdown(outputDir, timestamp, condition, output);
        }

        // Write raw LLM responses for manual review
        const rawLines = [];
        rawLines.push(`# Raw LLM Responses — ${condition}`);
        rawLines.push(`Model: ${modelConfig.api}/${modelConfig.model}`);
        rawLines.push(`Timestamp: ${new Date().toISOString()}`);
        rawLines.push('');
        for (const task of output.tasks) {
            rawLines.push(`${'='.repeat(70)}`);
            rawLines.push(`## ${task.slug} (${task.level}) — goal: ${task.goal_item}`);
            rawLines.push(`Parse: ${task.parse_success ? 'OK' : 'FAILED'}${task.error_type ? ` (${task.error_type})` : ''} | Strict: ${task.validation.strict_pass ? 'PASS' : 'FAIL'} | Lenient: ${task.validation.lenient_pass ? 'PASS' : 'FAIL'}`);
            if (task.validation.issues.length > 0) {
                rawLines.push(`Issues: ${task.validation.issues.join('; ')}`);
            }
            rawLines.push(`${'='.repeat(70)}`);
            rawLines.push('');
            if (task.raw_response) {
                rawLines.push(task.raw_response);
            } else {
                rawLines.push('(no response — parse failed or API error)');
            }
            rawLines.push('');
            rawLines.push('');
        }
        const rawPath = join(outputDir, `eval_${timestamp}_${condition}_raw.md`);
        writeFileSync(rawPath, rawLines.join('\n'));
        console.log(`Raw responses: ${rawPath}`);

        allSeedOutputs.push({ condition, output, seed });
    } // end condition loop

    } // end seed loop

    // Multi-seed merge: majority vote per task
    if (numSeeds > 1) {
        console.log('\n=== Multi-Seed Merge (Majority Vote) ===\n');
        const mergedByCondition = {};
        for (const { condition, output } of allSeedOutputs) {
            if (!mergedByCondition[condition]) mergedByCondition[condition] = [];
            mergedByCondition[condition].push(output);
        }
        for (const [condition, outputs] of Object.entries(mergedByCondition)) {
            // Collect per-slug vote counts across seeds
            const slugVotes = {};
            for (const output of outputs) {
                for (const task of output.tasks) {
                    if (!slugVotes[task.slug]) {
                        slugVotes[task.slug] = { level: task.level, strict: 0, lenient: 0, pvr: 0, total: 0 };
                    }
                    slugVotes[task.slug].strict  += task.validation.strict_pass  ? 1 : 0;
                    slugVotes[task.slug].lenient += task.validation.lenient_pass ? 1 : 0;
                    slugVotes[task.slug].pvr     += task.validation.pvr          ? 1 : 0;
                    slugVotes[task.slug].total++;
                }
            }

            // Majority vote: pass if strictly more than half the seeds pass
            const byLevel = {};
            let totalStrict = 0, totalLenient = 0, totalPvr = 0, totalTasks = 0;
            for (const [slug, v] of Object.entries(slugVotes)) {
                const threshold = v.total / 2;
                const strictPass  = v.strict  > threshold;
                const lenientPass = v.lenient > threshold;
                const pvrPass     = v.pvr     > threshold;
                const lvl = v.level;
                if (!byLevel[lvl]) byLevel[lvl] = { strict: 0, lenient: 0, pvr: 0, total: 0 };
                byLevel[lvl].strict  += strictPass  ? 1 : 0;
                byLevel[lvl].lenient += lenientPass ? 1 : 0;
                byLevel[lvl].pvr     += pvrPass     ? 1 : 0;
                byLevel[lvl].total++;
                totalStrict  += strictPass  ? 1 : 0;
                totalLenient += lenientPass ? 1 : 0;
                totalPvr     += pvrPass     ? 1 : 0;
                totalTasks++;
            }

            // Print per-level breakdown
            console.log(`${condition} (majority vote, ${outputs.length} seeds, ${totalTasks} tasks):`);
            for (const lvl of ['L1', 'L2', 'L3'].filter(l => byLevel[l])) {
                const v = byLevel[lvl];
                console.log(`  ${lvl}: ${v.strict}/${v.total} strict (${(100 * v.strict / v.total).toFixed(0)}%)`);
            }
            console.log(`  Overall: TCR=${totalStrict}/${totalTasks} (${(100 * totalStrict / totalTasks).toFixed(1)}%) | PVR=${totalPvr}/${totalTasks}`);

            // Save majority-vote summary JSON
            const mvData = {
                meta: {
                    condition,
                    seeds: outputs.length,
                    method: 'majority_vote',
                    timestamp: new Date().toISOString(),
                    model: outputs[0].meta.model
                },
                by_level: byLevel,
                overall: {
                    strict_tcr: `${totalStrict}/${totalTasks}`,
                    lenient_tcr: `${totalLenient}/${totalTasks}`,
                    pvr: `${totalPvr}/${totalTasks}`
                }
            };
            const mvPath = join(outputDir, `eval_${timestamp}_${condition}_majority_vote.json`);
            writeFileSync(mvPath, JSON.stringify(mvData, null, 2));
            console.log(`Majority vote results: ${mvPath}`);
        }
    }

    console.log('\n=== Evaluation complete ===');
}

// Only auto-run the CLI when this file is executed directly — importing
// validatePlanCorrectness() for offline re-scoring must not trigger a live eval.
if (import.meta.url === `file://${process.argv[1]}`) {
    main().catch(err => {
        console.error('Fatal error:', err);
        process.exit(1);
    });
}
