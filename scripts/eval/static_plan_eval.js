// ─── Model Creation ────────────────────────────────────────────────

function loadProfile(profileName) {
    // Try project root first (e.g. lucy.json), then profiles/ directory
    const candidates = [
        join(PROJECT_ROOT, `${profileName}.json`),
        join(PROJECT_ROOT, 'profiles', `${profileName}.json`)
    ];
    for (const p of candidates) {
        if (existsSync(p)) return JSON.parse(readFileSync(p, 'utf8'));
    }
    throw new Error(`Profile not found: tried ${candidates.join(', ')}`);
}

/**
 * Extract the enhancer model config from a profile.
 * Falls back to top-level model config if no enhancer section.
 */
function getModelConfig(profile) {
    if (profile.enhancer?.enhancer?.model) {
        return profile.enhancer.enhancer.model;
    }
    if (profile.enhancer?.model) {
        return profile.enhancer.model;
    }
    return profile.model;
}

async function createModel(modelConfig) {
    if (modelConfig.api === 'ollama') {
        return new Local(modelConfig.model, modelConfig.url);
    }
    if (modelConfig.api === 'doubao') {
        const { Doubao } = await import('../../src/models/doubao.js');
        return new Doubao(modelConfig.model, modelConfig.url);
    }
    if (modelConfig.api === 'deepseek') {
        const { DeepSeek } = await import('../../src/models/deepseek.js');
        return new DeepSeek(modelConfig.model, modelConfig.url, modelConfig.params || null);
    }
    if (modelConfig.api === 'openai') {
        // Official OpenAI API — reads OPENAI_API_KEY from keys.json or env
        const { GPT } = await import('../../src/models/gpt.js');
        return new GPT(modelConfig.model, modelConfig.url || null, modelConfig.params || null, modelConfig.proxy || null);
    }
    if (modelConfig.api === 'qwen') {
        // Use null URL to let Qwen class default to domestic endpoint
        // (keys.json key may not work with international endpoint)
        return new Qwen(modelConfig.model, null, modelConfig.params || null);
    }
    if (modelConfig.api === 'openrouter') {
        const { OpenRouter } = await import('../../src/models/openrouter.js');
        return new OpenRouter(modelConfig.model, modelConfig.url || null);
    }
    if (modelConfig.api === 'gemini') {
        const { Gemini } = await import('../../src/models/gemini.js');
        return new Gemini(modelConfig.model, modelConfig.url || null, modelConfig.params || null);
    }
    // Other OpenAI-compatible APIs — pass URL as-is
    return new Qwen(modelConfig.model, modelConfig.url, modelConfig.params || null);
}

